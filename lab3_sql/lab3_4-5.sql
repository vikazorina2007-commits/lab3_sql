-- ЗАДАНИЕ 4: Создать запросы для вывода


-- а) Фамилии всех заведующих отделений КООП вместе с адресом. 
-- Сортировка по адресу (ORDER BY).
SELECT фамилия_заведующего, адрес 
FROM отделение_кооп
ORDER BY адрес;

-- b) Все названия товаров.
SELECT наименование 
FROM товар;

-- c) Все различные адреса потребителей вместе с размером кредита.
-- Слово DISTINCT исключает дубликаты, если адреса и кредиты совпадают у разных людей.
SELECT DISTINCT адрес, кредит_проценты 
FROM потребитель;

-- ЗАДАНИЕ 5: Создать запросы для получения информации о:

-- а) Адресах и фамилиях потребителей, имеющих размер кредита более 2%:
SELECT адрес, фамилия 
FROM потребитель
WHERE кредит_проценты > 2;

-- b) Названиях и месте складирования товаров, стоимость единицы которых 
-- более 1000 руб., но не превышает 5000 руб. (используем BETWEEN):
SELECT наименование, склад 
FROM товар
WHERE цена_единицы BETWEEN 1000.01 AND 5000.00;

-- c) Фамилиях заведующих и адресах тех отделений КООП, которые расположены 
-- НЕ в Н.Новгороде и имеют размер комиссионных менее 4%. 
-- Вывод результатов организовать по названию (адресу) и размеру комиссионных.
SELECT фамилия_заведующего, адрес, комиссионные_проценты
FROM отделение_кооп
WHERE адрес <> 'Н.Новгород' AND комиссионные_проценты < 4
ORDER BY адрес, комиссионные_проценты;