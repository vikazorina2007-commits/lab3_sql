-- ЗАДАНИЕ 8: Модификация значений (UPDATE)
-- ==========================================

-- Изменяем столбец итого_руб с учетом кредитных процентов потребителя
UPDATE закупки z
SET итого_руб = z.итого_руб * (1 + p.кредит_проценты / 100.0)
FROM потребитель p
WHERE z.потребитель_id = p.идентификатор;

-- Выводим измененную таблицу для отчета
SELECT * FROM закупки;

-- ==========================================
-- ЗАДАНИЕ 9: Добавление столбца и расчет комиссионных (ALTER + UPDATE)
-- ==========================================

-- 9.а) Добавляем новую колонку комиссионные_руб в структуру таблицы
ALTER TABLE закупки 
ADD COLUMN комиссионные_руб NUMERIC(12, 2);

-- 9.б) Рассчитываем и вносим значения комиссионных во все строки
UPDATE закупки z
SET комиссионные_руб = z.итого_руб * (o.комиссионные_проценты / 100.0)
FROM отделение_кооп o
WHERE z.отделение_кооп_id = o.идентификатор;

-- 9.в) Выводим итоговую таблицу закупки, чтобы показать новый столбец преподавателю
SELECT * FROM закупки;