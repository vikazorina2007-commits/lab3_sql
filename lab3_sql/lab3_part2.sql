-- ЗАДАНИЕ 13: Использование операции EXISTS (NOT EXISTS)
-- =========================================================================

-- а) Найти те отделения КООП, которые снабжали всех потребителей из Заволжья
SELECT o.фамилия_заведующего, o.адрес 
FROM отделение_кооп o
WHERE NOT EXISTS (
    SELECT p.идентификатор FROM потребитель p 
    WHERE p.адрес = 'Заволжье' AND NOT EXISTS (
        SELECT z.номер_договора FROM закупки z 
        WHERE z.отделение_кооп_id = o.идентификатор AND z.потребитель_id = p.идентификатор
    )
);

-- b) Какие товары покупали все потребители более раза
SELECT t.наименование 
FROM товар t
WHERE NOT EXISTS (
    SELECT p.идентификатор FROM потребитель p 
    WHERE NOT EXISTS (
        SELECT z.номер_договора FROM закупки z 
        WHERE z.товар_id = t.идентификатор AND z.потребитель_id = p.идентификатор
        HAVING COUNT(z.номер_договора) > 1
    )
);

-- c) Найти потребителей, не покупавших товаров с ценой более 4000 руб.
SELECT p.фамилия 
FROM потребитель p
WHERE NOT EXISTS (
    SELECT 1 FROM закупки z
    JOIN товар t ON z.товар_id = t.идентификатор
    WHERE z.потребитель_id = p.идентификатор AND t.цена_единицы > 4000.00
);

-- d) Найти товары, которые продавали все отделения КООП всем потребителям с кредитом более 2%
SELECT t.наименование 
FROM товар t
WHERE NOT EXISTS (
    SELECT o.идентификатор FROM отделение_кооп o
    WHERE NOT EXISTS (
        SELECT 1 FROM закупки z
        JOIN потребитель p ON z.потребитель_id = p.идентификатор
        WHERE z.товар_id = t.идентификатор 
          AND z.отделение_кооп_id = o.идентификатор 
          AND p.кредит_проценты > 2
    )
);

