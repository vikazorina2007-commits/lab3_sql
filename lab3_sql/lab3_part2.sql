-- =========================================================================

-- а) Найти среди товаров, купленных потребителями из Тарасихи, оставшийся в наименьшем количестве
SELECT t.наименование, z.кол_во
FROM закупки z
JOIN товар t ON z.товар_id = t.идентификатор
JOIN потребитель p ON z.потребитель_id = p.идентификатор
WHERE p.адрес = 'Тарасиха' AND z.кол_во <= ALL (
    SELECT z2.кол_во 
    FROM закупки z2
    JOIN потребитель p2 ON z2.потребитель_id = p2.идентификатор
    WHERE p2.адрес = 'Тарасиха'
);

-- b) Есть ли закупки, имеющие наибольшую итоговую сумму при наименьшем количестве купленного товара
SELECT номер_договора, итого_руб, кол_во
FROM закупки
WHERE итого_руб >= ALL (SELECT итого_руб FROM закупки)
  AND кол_во <= ANY (SELECT кол_во FROM закупки);

-- c) Запрос задания 7.d, переписанный через ALL/ANY
-- (Данные по покупке товаров, которые складировались и покупались в одном районе)
SELECT z.номер_договора, z.дата, z.итого_руб
FROM закупки z
WHERE z.товар_id = ANY (
    SELECT t.идентификатор 
    FROM товар t
    JOIN отделение_кооп o ON t.склад = o.адрес
    WHERE o.идентификатор = z.отделение_кооп_id
)
ORDER BY z.итого_руб ASC;

-- d) Найти потребителя с наибольшей кредитоспособностью среди тех, кто покупал товары в Нижегородских отделениях КООП
SELECT DISTINCT p.фамилия, p.кредит_проценты
FROM закупки z
JOIN потребитель p ON z.потребитель_id = p.идентификатор
JOIN отделение_кооп o ON z.отделение_кооп_id = o.идентификатор
WHERE o.адрес = 'Н.Новгород' AND p.кредит_проценты >= ALL (
    SELECT p2.кредит_проценты
    FROM закупки z2
    JOIN потребитель p2 ON z2.потребитель_id = p2.идентификатор
    JOIN отделение_кооп o2 ON z2.отделение_кооп_id = o2.идентификатор
    WHERE o2.адрес = 'Н.Новгород'
);

