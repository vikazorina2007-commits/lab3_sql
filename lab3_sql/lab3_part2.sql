-- а) Определить для каждого наименования товара средний размер кредита потребителей, бравших этот товар в отделениях Н.Новгорода
SELECT t.наименование, AVG(p.кредит_проценты) AS средний_кредит_потребителей
FROM закупки z
JOIN товар t ON z.товар_id = t.идентификатор
JOIN потребитель p ON z.потребитель_id = p.идентификатор
JOIN отделение_кооп o ON z.отделение_кооп_id = o.идентификатор
WHERE o.адрес = 'Н.Новгород'
GROUP BY t.наименование;

-- b) Для всех отделений КООП определить общее число проведенных заказов
SELECT o.фамилия_заведующего, o.адрес, COUNT(z.номер_договора) AS общее_число_заказов
FROM отделение_кооп o
LEFT JOIN закупки z ON z.отделение_кооп_id = o.идентификатор
GROUP BY o.фамилия_заведующего, o.адрес;

-- c) Найти покупателей, которые в мае приобрели товаров на сумму более 80000 в отделениях КООП с комиссионными более 3%
SELECT p.фамилия, SUM(z.итого_руб) AS общая_сумма_в_мае
FROM закупки z
JOIN потребитель p ON z.потребитель_id = p.идентификатор
JOIN отделение_кооп o ON z.отделение_кооп_id = o.идентификатор
WHERE z.дата = 'Май' AND o.комиссионные_проценты >= 3
GROUP BY p.фамилия
HAVING SUM(z.итого_руб) > 80000.00;

-- d) В какие месяцы общее число заказов превышало четыре
SELECT дата AS месяц, COUNT(номер_договора) AS количество_заказов
FROM закупки
GROUP BY дата
HAVING COUNT(номер_договора) > 4;