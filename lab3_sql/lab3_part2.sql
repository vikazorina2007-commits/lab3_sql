-- а) Какие заведующие имеют такие же комиссионные, как и Ильин
-- (Ищем всех с такими же %, исключая самого Ильина)
SELECT фамилия_заведующего 
FROM отделение_кооп
WHERE комиссионные_проценты IN (
    SELECT комиссионные_проценты 
    FROM отделение_кооп 
    WHERE фамилия_заведующего = 'Ильин'
) AND фамилия_заведующего <> 'Ильин';

-- b) Запрос задания 7.а, переписанный через оператор IN
-- (Номер договора, дата, фамилия потребителей, купивших ведра или с суммой >= 20000 руб.)
SELECT z.номер_договора, z.дата, p.фамилия
FROM закупки z
JOIN потребитель p ON z.потребитель_id = p.идентификатор
WHERE z.товар_id IN (
    SELECT идентификатор FROM товар WHERE наименование = 'Ведро оцинкованное'
) OR z.итого_руб >= 20000.00;

-- c) Какие покупки не производились с марта месяца
-- (Выбираем месяцы, которые не входят в весенне-летний период)
SELECT номер_договора, дата 
FROM закупки
WHERE дата NOT IN ('Март', 'Апрель', 'Май', 'Июнь', 'Июль');

