-- а) Найти среди отделений КООП, продававших товары всем потребителям из Заволжья те, которые имеют комиссионные больше средних
SELECT o.фамилия_заведующего, o.комиссионные_проценты
FROM отделение_кооп o
WHERE o.комиссионные_проценты > (SELECT AVG(комиссионные_проценты) FROM отделение_кооп);

-- b) Сколько различных товаров заказали потребители с минимальным кредитом
SELECT COUNT(DISTINCT z.товар_id) AS количество_различных_товаров
FROM закупки z
WHERE z.потребитель_id IN (
    SELECT идентификатор FROM потребитель WHERE кредит_проценты = (SELECT MIN(кредит_проценты) FROM потребитель)
);

-- c) Найти общую стоимость всех проданных в мае товаров
SELECT SUM(итого_руб) AS общая_стоимость_май 
FROM закупки 
WHERE дата = 'Май';

-- d) Сколько всего было продано за весенний период
SELECT SUM(кол_во) AS всего_продано_за_весну 
FROM закупки 
WHERE дата IN ('Март', 'Апрель', 'Май');

