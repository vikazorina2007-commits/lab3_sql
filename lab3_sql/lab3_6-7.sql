-- ЗАДАНИЕ 6: Для каждой записи о закупках вывести данные:
-- ==========================================

-- а) Фамилия потребителя, дата, название товара;
SELECT p.фамилия AS фамилия_потребителя, z.дата, t.наименование AS название_товара
FROM закупки z
JOIN потребитель p ON z.потребитель_id = p.идентификатор
JOIN товар t ON z.товар_id = t.идентификатор;

-- b) Дата, фамилия зав. отделением КООП, название и количество закупленных товаров.
SELECT z.дата, o.фамилия_заведующего, t.наименование AS название_товара, z.кол_во
FROM закупки z
JOIN отделение_кооп o ON z.отделение_кооп_id = o.идентификатор
JOIN товар t ON z.товар_id = t.идентификатор;

-- ==========================================
-- ЗАДАНИЕ 7: Определить:
-- ==========================================

-- а) Номер договора, дату, фамилию потребителей, купивших ведра или сделавших заказ на общую сумму не менее 20000руб.
-- (Ищем строго по названию 'Ведро оцинкованное', как требуют правила лабы)
SELECT z.номер_договора, z.дата, p.фамилия
FROM закупки z
JOIN потребитель p ON z.потребитель_id = p.идентификатор
JOIN товар t ON z.товар_id = t.идентификатор
WHERE t.наименование = 'Ведро оцинкованное' OR z.итого_руб >= 20000.00;

-- b) Идентификаторы, адреса и фамилии заведующих тех отделений КООП, в которых 
-- покупали товары потребители с кредитом более 2% после января;
-- (Исключаем текстовый 'Январь')
SELECT DISTINCT o.идентификатор, o.адрес, o.фамилия_заведующего
FROM закупки z
JOIN отделение_кооп o ON z.отделение_кооп_id = o.идентификатор
JOIN потребитель p ON z.потребитель_id = p.идентификатор
WHERE p.кредит_проценты > 2 AND z.дата <> 'Январь';

-- c) Фамилии потребителей, живущих не в Тарасихе, которые покупали товары в тех 
-- отделениях, где размер комиссионных более 4%;
SELECT DISTINCT p.фамилия
FROM закупки z
JOIN потребитель p ON z.потребитель_id = p.идентификатор
JOIN отделение_кооп o ON z.отделение_кооп_id = o.идентификатор
WHERE p.адрес <> 'Тарасиха' AND o.комиссионные_проценты > 4;

-- d) Данные по покупке товаров, которые складировались и покупались в одном районе. 
-- Включить данные о стоимости и отсортировать по возрастанию суммы (ASC).
SELECT z.номер_договора, z.дата, t.наименование, z.итого_руб
FROM закупки z
JOIN товар t ON z.товар_id = t.идентификатор
JOIN отделение_кооп o ON z.отделение_кооп_id = o.идентификатор
WHERE t.склад = o.адрес
ORDER BY z.итого_руб ASC;